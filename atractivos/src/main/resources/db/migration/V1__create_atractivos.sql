CREATE TABLE atractivo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(150) NOT NULL,
    descripcion   VARCHAR(2000),
    categoria     VARCHAR(60)  NOT NULL,
    estado        VARCHAR(20)  NOT NULL,
    gestor_id     BIGINT       NOT NULL,
    creado_en     TIMESTAMPTZ  NOT NULL,

    CONSTRAINT ck_atractivo_estado CHECK (estado IN ('ABIERTO', 'RESTRINGIDO', 'CERRADO'))
);

CREATE INDEX idx_atractivo_categoria ON atractivo (categoria);

-- Historial de alertas de seguridad (append-only).
CREATE TABLE alerta_seguridad (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atractivo_id  BIGINT       NOT NULL,
    mensaje       VARCHAR(500) NOT NULL,
    emitida_por   BIGINT       NOT NULL,
    emitida_en    TIMESTAMPTZ  NOT NULL,

    CONSTRAINT fk_alerta_atractivo FOREIGN KEY (atractivo_id) REFERENCES atractivo (id)
);
