CREATE TABLE cuenta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(180)  NOT NULL,
    password_hash   VARCHAR(100)  NOT NULL,
    nombre          VARCHAR(120)  NOT NULL,
    activa          BOOLEAN       NOT NULL DEFAULT TRUE,
    modo_operador   BOOLEAN       NOT NULL DEFAULT FALSE,
    creada_en       TIMESTAMPTZ   NOT NULL,

    CONSTRAINT uk_cuenta_email UNIQUE (email)
);

CREATE TABLE cuenta_rol (
    cuenta_id   BIGINT      NOT NULL,
    rol         VARCHAR(20) NOT NULL,

    CONSTRAINT pk_cuenta_rol PRIMARY KEY (cuenta_id, rol),
    CONSTRAINT fk_cuenta_rol_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuenta (id),
    CONSTRAINT ck_cuenta_rol_valor CHECK (rol IN ('TURISTA', 'OPERADOR', 'GESTOR', 'ADMIN'))
);
