-- Refresh tokens opacos (POST /api/auth/refresh y /api/auth/logout). Solo se guarda el hash SHA-256:
-- una fuga de la base no permite usar los tokens. Rotacion: cada uso revoca el token y emite uno nuevo.
CREATE TABLE refresh_token (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id    BIGINT       NOT NULL,
    token_hash   VARCHAR(64)  NOT NULL,
    emitido_en   TIMESTAMPTZ  NOT NULL,
    expira_en    TIMESTAMPTZ  NOT NULL,
    revocado_en  TIMESTAMPTZ,

    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_token_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuenta (id),
    CONSTRAINT ck_refresh_token_vigencia CHECK (expira_en > emitido_en)
);

-- Revocacion masiva por cuenta (cambio de modo, suspension, reutilizacion detectada).
CREATE INDEX idx_refresh_token_cuenta_activo ON refresh_token (cuenta_id) WHERE revocado_en IS NULL;
