-- Proyeccion local de las reservas pagables. Se alimenta por eventos (ReservaAceptada, ReservaCancelada);
-- Pagos nunca lee tablas de Reservas.
CREATE TABLE reserva_pagable (
    reserva_id     BIGINT        PRIMARY KEY,
    turista_id     BIGINT        NOT NULL,
    valor_a_pagar  NUMERIC(12,2) NOT NULL,
    plazo_pago     TIMESTAMPTZ   NOT NULL,
    cancelada      BOOLEAN       NOT NULL DEFAULT FALSE,

    CONSTRAINT ck_reserva_pagable_valor CHECK (valor_a_pagar >= 0)
);

CREATE TABLE pago (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version               BIGINT        NOT NULL DEFAULT 0,
    reserva_id            BIGINT        NOT NULL,
    turista_id            BIGINT        NOT NULL,
    monto                 NUMERIC(12,2) NOT NULL,
    estado                VARCHAR(20)   NOT NULL,
    referencia_pasarela   VARCHAR(100)  NOT NULL,
    creado_en             TIMESTAMPTZ   NOT NULL,
    aprobado_en           TIMESTAMPTZ,

    -- Idempotencia: un mismo webhook o referencia nunca crea dos pagos (RNF Consistencia).
    CONSTRAINT uk_pago_referencia UNIQUE (referencia_pasarela),
    CONSTRAINT ck_pago_estado CHECK (estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'REEMBOLSADO')),
    CONSTRAINT ck_pago_monto CHECK (monto >= 0)
);

-- Una sola aprobacion por reserva, aun con reintentos de la pasarela (RF-PAG-05).
CREATE UNIQUE INDEX uk_pago_reserva_aprobado ON pago (reserva_id) WHERE estado = 'APROBADO';
CREATE INDEX idx_pago_turista ON pago (turista_id, creado_en);
CREATE INDEX idx_pago_reserva ON pago (reserva_id);
