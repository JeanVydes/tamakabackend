-- Registros de demanda construidos a partir de eventos. Solo datos propios (sin acceso a otros esquemas).
-- Lectura de reportes: en produccion podra apuntar a una replica de lectura del mismo esquema.
CREATE TABLE registro_demanda (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo          VARCHAR(40)  NOT NULL,
    operador_id   BIGINT,
    referencia_id BIGINT       NOT NULL,
    dia           DATE         NOT NULL,
    ocurrido_en   TIMESTAMPTZ  NOT NULL,

    CONSTRAINT ck_demanda_tipo CHECK (tipo IN ('RESERVA_SOLICITADA', 'PAGO_APROBADO', 'RESERVA_CANCELADA'))
);

CREATE INDEX idx_demanda_dia_tipo ON registro_demanda (dia, tipo);
CREATE INDEX idx_demanda_operador_dia ON registro_demanda (operador_id, dia);
