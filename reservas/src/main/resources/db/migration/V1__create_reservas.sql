CREATE TABLE solicitud_reserva (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version              BIGINT        NOT NULL DEFAULT 0,
    turista_id           BIGINT        NOT NULL,
    servicio_id          BIGINT        NOT NULL,
    operador_id         BIGINT        NOT NULL,
    fecha_reserva        DATE          NOT NULL,
    numero_personas      INTEGER       NOT NULL,
    estado               VARCHAR(20)   NOT NULL,
    valor_a_pagar        NUMERIC(12,2),
    observacion_operador VARCHAR(500),
    creada_en            TIMESTAMPTZ   NOT NULL,
    respondida_en        TIMESTAMPTZ,
    plazo_pago           TIMESTAMPTZ,

    CONSTRAINT ck_reserva_estado CHECK (estado IN ('PENDIENTE', 'ACEPTADA', 'RECHAZADA', 'CANCELADA', 'CONFIRMADA', 'FINALIZADA')),
    CONSTRAINT ck_reserva_personas CHECK (numero_personas >= 1),
    CONSTRAINT ck_reserva_valor CHECK (valor_a_pagar IS NULL OR valor_a_pagar >= 0)
);

CREATE INDEX idx_reserva_turista_estado ON solicitud_reserva (turista_id, estado);
CREATE INDEX idx_reserva_servicio_estado ON solicitud_reserva (servicio_id, estado);
CREATE INDEX idx_reserva_operador_estado ON solicitud_reserva (operador_id, estado);
CREATE INDEX idx_reserva_timeouts ON solicitud_reserva (estado, creada_en);

-- Historial append-only de transiciones (RNF Auditoria).
CREATE TABLE historial_estado_reserva (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id      BIGINT       NOT NULL,
    estado_anterior VARCHAR(20),
    estado_nuevo    VARCHAR(20)  NOT NULL,
    motivo          VARCHAR(300),
    ocurrido_en     TIMESTAMPTZ  NOT NULL,

    CONSTRAINT fk_historial_reserva FOREIGN KEY (reserva_id) REFERENCES solicitud_reserva (id)
);
