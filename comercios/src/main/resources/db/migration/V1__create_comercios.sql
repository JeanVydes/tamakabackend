CREATE TABLE comercio (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operador_id  BIGINT        NOT NULL,
    nombre       VARCHAR(150)  NOT NULL,
    rnt          VARCHAR(50)   NOT NULL,
    categoria    VARCHAR(60)   NOT NULL,
    descripcion  VARCHAR(1000),
    activo       BOOLEAN       NOT NULL DEFAULT TRUE,
    creado_en    TIMESTAMPTZ   NOT NULL,

    CONSTRAINT uk_comercio_rnt UNIQUE (rnt)
);

CREATE INDEX idx_comercio_operador ON comercio (operador_id);
CREATE INDEX idx_comercio_categoria ON comercio (categoria) WHERE activo;

CREATE TABLE servicio (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comercio_id   BIGINT        NOT NULL,
    nombre        VARCHAR(150)  NOT NULL,
    precio_base   NUMERIC(12,2) NOT NULL,
    min_personas  INTEGER       NOT NULL,
    max_personas  INTEGER       NOT NULL,
    activo        BOOLEAN       NOT NULL DEFAULT TRUE,
    atributos     JSONB         NOT NULL DEFAULT '{}'::jsonb,

    CONSTRAINT fk_servicio_comercio FOREIGN KEY (comercio_id) REFERENCES comercio (id),
    CONSTRAINT ck_servicio_precio CHECK (precio_base >= 0),
    CONSTRAINT ck_servicio_personas CHECK (min_personas >= 1 AND max_personas >= min_personas)
);

CREATE INDEX idx_servicio_comercio ON servicio (comercio_id);
